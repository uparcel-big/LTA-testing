// Helper to generate realistic hourly trend for a carpark
function generateHourlyTrends(peakOccupancy: number, currentAvailable: number, total: number) {
  const hours = ['06:00', '08:00', '10:00', '12:00', '14:00', '16:00', '18:00', '20:00', '22:00'];
  return hours.map((hour, idx) => {
    // Peak hours: 12-14 and 18-20
    const factor = idx === 3 || idx === 6 ? 1 : idx === 0 || idx === 8 ? 0.4 : 0.75;
    const occ = Math.min(98, Math.max(15, Math.round(peakOccupancy * factor + (Math.random() * 8 - 4))));
    const avail = Math.max(0, Math.round(total * (1 - occ / 100)));
    return {
      hour,
      occupancyPercent: occ,
      availableCars: avail,
    };
  });
}

